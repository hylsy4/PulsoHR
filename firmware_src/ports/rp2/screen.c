void i2c_bus_init() {
    i2c_init(I2C_PORT, I2C_FREQ);
    gpio_set_function(SDA_PIN, GPIO_FUNC_I2C);
    gpio_set_function(SCL_PIN, GPIO_FUNC_I2C);
    gpio_pull_up(SDA_PIN);
    gpio_pull_up(SCL_PIN);
    uint8_t init_cmds[] = {
        0x00,

        0xAE,             // display off
        0x20, 0x00,       // horizontal addressing mode
        0xA8, 0x3F,       // multiplex 1/64
        0xD3, 0x00,       // display offset
        0x40,             // start line
        0xA1,             // segment remap
        0xC8,             // COM scan direction
        0xDA, 0x12,       // COM pins
        0x81, 0x7F,       // contrast
        0xA4,             // display RAM
        0xA6,             // normal display
        0xD5, 0x80,       // clock
        0x8D, 0x14,       // charge pump
        0xAF              // display on
    };
    i2c_write_blocking(I2C_PORT, SCREEN_ADDR, init_cmds, sizeof(init_cmds), false);
}

void send_frame(uint8_t *data, size_t len) {
    uint8_t buffer[len + 1];
    buffer[0] = 0x40;
    for (size_t i = 0; i < len; i++) {
        buffer[i + 1] = data[i];
    }
    i2c_write_blocking(I2C_PORT, SCREEN_ADDR, buffer, len + 1, false);
}

void set_fullscreen_draw() {
    uint8_t x[] = {
        0x00,
        0x21, 0, 127,
        0x22, 0, 7
    };
    i2c_write_blocking(I2C_PORT, SCREEN_ADDR, x, sizeof(x), false);
}

void screen_white() {
    uint8_t buffer[1024];

    for (int i = 0; i < 1024; i++) {
        buffer[i] = 0xFF;
    }

    set_fullscreen_draw();
    send_frame(buffer, 1024);
}

void screen_logo() {
    set_fullscreen_draw();
    send_frame(logo_buffer, 1024);
}
